#!/usr/bin/env node
// Reports whether `pnpm link:on` is currently active by checking for the
// GENERATED marker at the top of pnpm-workspace.yaml. Invoked by
// `pnpm link:status`.

import { existsSync, readFileSync } from 'node:fs'

const TARGET = 'pnpm-workspace.yaml'
const MARKER = '# GENERATED by scripts/apply-workspace-overlay.mjs'

if (!existsSync(TARGET)) {
  console.error(`[status] ${TARGET} not found in current directory.`)
  process.exit(1)
}

const firstLine = readFileSync(TARGET, 'utf8').split('\n', 1)[0]
if (firstLine.startsWith(MARKER)) {
  console.log('link mode — pnpm link:on')
} else {
  console.log('release mode — pnpm link:off')
}
