#!/usr/bin/env node
// Restores pnpm-workspace.yaml from the git index. Aborts if a previously
// applied overlay has leaked into the index or HEAD, since `git checkout`
// would otherwise reinstate the polluted version silently. Invoked by
// `pnpm link:off`.

import { execSync } from 'node:child_process'

const TARGET = 'pnpm-workspace.yaml'
const MARKER = '# GENERATED by scripts/apply-workspace-overlay.mjs'

function run(cmd) {
  return execSync(cmd, { encoding: 'utf8' })
}

function checkClean(rev, label) {
  try {
    const content = run(`git show ${rev}:${TARGET}`)
    if (content.includes(MARKER)) {
      console.error(`[restore] ${label} copy of ${TARGET} contains the GENERATED marker.`)
      console.error(`[restore] A merged overlay was committed/staged. Cannot safely restore.`)
      console.error(`[restore] Recover by:`)
      console.error(`[restore]   1. git log --oneline -- ${TARGET}`)
      console.error(`[restore]   2. Pick the last commit that did NOT contain the overlay.`)
      console.error(`[restore]   3. git show <clean-sha>:${TARGET} > ${TARGET}`)
      console.error(`[restore]   4. git add ${TARGET} && git commit -m 'chore: restore clean ${TARGET}'`)
      process.exit(1)
    }
  } catch (err) {
    console.error(`[restore] Could not read ${label} (${rev}:${TARGET}):`, err.message)
    process.exit(1)
  }
}

checkClean('HEAD', 'HEAD')
checkClean(':0', 'index')

run(`git checkout -- ${TARGET}`)
console.log(`[restore] ${TARGET} restored from git index.`)
