#!/usr/bin/env node
/**
 * Bundle each ReScript slot module into the one file a deployment serves.
 *
 * A slot module written in ReScript compiles to imports a browser cannot follow:
 * `@rescript/runtime/…` for the stdlib and `@reventlessdev/reventless-ui-slots/…`
 * for the contract. The shell fetches `uiSlotsUrl` from the served origin and
 * `import()`s it with no bundler and no import map in between, so those have to
 * be resolved ahead of time and inlined.
 *
 * `react` is the one thing that must NOT be. A slot module builds its elements
 * with the shell's own `createElement`, handed to `register` as an argument, so
 * a correct module never imports React at all — and bundling a second copy is
 * how a renderer's hooks end up on the wrong dispatcher. Nothing here marks it
 * external, deliberately: if React ever reaches the graph, this fails loudly
 * rather than quietly shipping two of them.
 *
 * Output is readable rather than minified. It is the file that decides what a
 * deployment looks like, it is committed, and a diff nobody can read is one
 * nobody reviews.
 *
 * Usage: node scripts/bundle-slot-modules.mjs
 */

import { build, context } from 'esbuild'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')

// Each ReScript slot module and the file a deployment declares as its
// `uiSlotsFile`. Listed rather than discovered, the bargain `check-trait-pack`
// makes with its pairs: the declaration lives in ReScript, and reading it out
// would be a parser to keep in step with the language.
const MODULES = [
  {
    entry: 'examples/online-shop-hybrid/seed-data/src/StorefrontSlots.res.mjs',
    out: 'examples/online-shop-hybrid/seed-data/dist/storefront-slots.js',
  },
]

// `--watch` re-bundles whenever ReScript rewrites the compiled output, which is
// what keeps the dev loop honest: the platform watches the BUNDLE, so without
// this a developer edits the `.res`, sees the compile succeed, and is served the
// previous bundle with no sign that anything went stale.
const watch = process.argv.includes('--watch')

let failed = false

for (const { entry, out } of MODULES) {
  const entryPath = join(repoRoot, entry)
  if (!existsSync(entryPath)) {
    console.error(
      `✗ ${entry}\n` +
      `  not compiled. Run \`pnpm run build\` first — this bundles ReScript output,\n` +
      `  it does not produce it.`,
    )
    failed = true
    continue
  }

  const options = {
    entryPoints: [entryPath],
    outfile: join(repoRoot, out),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    // Readable on purpose — see the note above.
    minify: false,
    // A slot module is one `register` export; nothing imports it at build
    // time, so without this esbuild would treat the export as unused.
    treeShaking: true,
    logLevel: 'warning',
    banner: {
      js:
        '// Generated by scripts/bundle-slot-modules.mjs from ' +
        `${entry.split('/').pop()} — do not edit.\n` +
        '// This is the file a deployment serves at config.uiSlotsUrl.',
    },
  }

  try {
    if (watch) {
      const ctx = await context(options)
      await ctx.watch()
      console.log(`watching ${entry} → ${out}`)
    } else {
      await build(options)
      console.log(`ok ${out}`)
    }
  } catch (error) {
    console.error(`✗ ${entry}\n  ${error.message}`)
    failed = true
  }
}

if (failed) {
  console.error('\nSlot module bundling failed.')
  process.exit(1)
}
