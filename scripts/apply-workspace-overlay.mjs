#!/usr/bin/env node
// Merges pnpm-workspace.local.yaml onto the committed pnpm-workspace.yaml
// so a gitignored overlay can add sibling-repo workspace packages (link
// mode) without editing the committed config. Invoked by `pnpm link:on`.
// Committed HEAD version is the source of truth. Run `pnpm link:off` to
// restore it (git checkout pnpm-workspace.yaml).
//
// If overlay.overrides is set, those entries are also merged into
// package.json's pnpm.overrides (the location pnpm actually reads) and
// restored by restore-workspace-base.mjs.

import { execSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

import { parse, stringify } from 'yaml'

const OVERLAY = 'pnpm-workspace.local.yaml'
const TARGET = 'pnpm-workspace.yaml'
const PKG = 'package.json'
const MARKER = '# GENERATED by scripts/apply-workspace-overlay.mjs'

const baseYaml = execSync(`git show HEAD:${TARGET}`, { encoding: 'utf8' })
if (baseYaml.includes(MARKER)) {
  console.error(`[overlay] HEAD's ${TARGET} contains the GENERATED marker.`)
  console.error(`[overlay] A previous \`pnpm link:on\` output was committed, so`)
  console.error(`[overlay] the source-of-truth base is lost. Recover by:`)
  console.error(`[overlay]   1. git log --oneline -- ${TARGET}`)
  console.error(`[overlay]   2. Pick the last commit that did NOT contain the overlay.`)
  console.error(`[overlay]   3. git show <clean-sha>:${TARGET} > ${TARGET}`)
  console.error(`[overlay]   4. git add ${TARGET} && git commit -m 'chore: restore clean ${TARGET}'`)
  console.error(`[overlay] Then rerun \`pnpm link:on\`.`)
  process.exit(1)
}
const base = parse(baseYaml)

if (!existsSync(OVERLAY)) {
  console.error(`[overlay] ${OVERLAY} not found.`)
  console.error(`[overlay] Copy ${OVERLAY}.example to ${OVERLAY} and edit it.`)
  process.exit(1)
}

const overlay = parse(readFileSync(OVERLAY, 'utf8')) ?? {}
const merged = { ...base }

if (Array.isArray(overlay.packages)) {
  const existing = new Set(base.packages ?? [])
  const additions = overlay.packages.filter((p) => !existing.has(p))
  merged.packages = [...(base.packages ?? []), ...additions]
}

if (overlay.overrides) {
  merged.overrides = { ...(base.overrides ?? {}), ...overlay.overrides }

  // pnpm reads overrides from package.json pnpm.overrides, not pnpm-workspace.yaml.
  // Merge overlay overrides there too so pnpm install picks them up.
  const pkg = JSON.parse(readFileSync(PKG, 'utf8'))
  pkg.pnpm = pkg.pnpm ?? {}
  pkg.pnpm.overrides = { ...(pkg.pnpm.overrides ?? {}), ...overlay.overrides }
  writeFileSync(PKG, JSON.stringify(pkg, null, 2) + '\n')
  console.log(`[overlay] Merged overrides into ${PKG}`)
}

if (overlay.onlyBuiltDependencies) {
  console.warn(`[overlay] Warning: overlay defines onlyBuiltDependencies; normally this belongs in the committed file.`)
  merged.onlyBuiltDependencies = [
    ...new Set([...(base.onlyBuiltDependencies ?? []), ...overlay.onlyBuiltDependencies]),
  ]
}

const header = `# GENERATED by scripts/apply-workspace-overlay.mjs — do NOT edit directly.
# Edit the committed version (in git) for release-mode changes.
# Edit pnpm-workspace.local.yaml + rerun \`pnpm link:on\` for link-mode changes.
# Restore release mode with \`pnpm link:off\`.

`

writeFileSync(TARGET, header + stringify(merged))
console.log(`[overlay] Applied ${OVERLAY} → ${TARGET}`)
