#!/usr/bin/env node
// Merges pnpm-workspace.local.yaml onto pnpm-workspace.base.yaml and
// writes the result to pnpm-workspace.yaml (gitignored), so a developer
// can activate sibling-repo links without modifying any tracked file.
// Invoked by `pnpm link:on`.
//
// If overlay.overrides is set, those entries are also merged into
// package.json's pnpm.overrides (the location pnpm actually reads) and
// restored by restore-workspace-base.mjs.

import { existsSync, lstatSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'

import { parse, stringify } from 'yaml'

const BASE = 'pnpm-workspace.base.yaml'
const OVERLAY = 'pnpm-workspace.local.yaml'
const TARGET = 'pnpm-workspace.yaml'
const PKG = 'package.json'

if (!existsSync(BASE)) {
  console.error(`[overlay] ${BASE} not found. Are you in the repo root?`)
  process.exit(1)
}

if (!existsSync(OVERLAY)) {
  console.error(`[overlay] ${OVERLAY} not found.`)
  console.error(`[overlay] Copy ${OVERLAY}.example to ${OVERLAY} and edit it.`)
  process.exit(1)
}

const base = parse(readFileSync(BASE, 'utf8'))
const overlay = parse(readFileSync(OVERLAY, 'utf8')) ?? {}
const merged = { ...base }

if (Array.isArray(overlay.packages)) {
  const existing = new Set(base.packages ?? [])
  const additions = overlay.packages.filter((p) => !existing.has(p))
  merged.packages = [...(base.packages ?? []), ...additions]
}

if (overlay.overrides) {
  merged.overrides = { ...(base.overrides ?? {}), ...overlay.overrides }

  // pnpm reads overrides from package.json pnpm.overrides, not pnpm-workspace.yaml.
  // Merge overlay overrides there too so pnpm install picks them up.
  const pkg = JSON.parse(readFileSync(PKG, 'utf8'))
  pkg.pnpm = pkg.pnpm ?? {}
  pkg.pnpm.overrides = { ...(pkg.pnpm.overrides ?? {}), ...overlay.overrides }
  writeFileSync(PKG, JSON.stringify(pkg, null, 2) + '\n')
  console.log(`[overlay] Merged overrides into ${PKG}`)
}

if (overlay.onlyBuiltDependencies) {
  console.warn(`[overlay] Warning: overlay defines onlyBuiltDependencies; normally this belongs in the base file.`)
  merged.onlyBuiltDependencies = [
    ...new Set([...(base.onlyBuiltDependencies ?? []), ...overlay.onlyBuiltDependencies]),
  ]
}

// Replace whatever is at TARGET (typically a symlink to BASE) with the merged file.
if (existsSync(TARGET) || lstatSync(TARGET, { throwIfNoEntry: false })) {
  try {
    unlinkSync(TARGET)
  } catch (err) {
    if (err.code !== 'ENOENT') throw err
  }
}

const header = `# GENERATED by scripts/apply-workspace-overlay.mjs — link mode.
# This file is gitignored. Edit ${BASE} for release-mode changes.
# Edit ${OVERLAY} + rerun \`pnpm link:on\` for link-mode changes.
# Run \`pnpm link:off\` to restore release mode (symlink back to ${BASE}).

`

writeFileSync(TARGET, header + stringify(merged))
console.log(`[overlay] Wrote link-mode ${TARGET} from ${BASE} + ${OVERLAY}.`)
